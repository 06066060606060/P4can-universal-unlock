from pathlib import Path
import gzip
root = Path(__file__).resolve().parents[1]
data = gzip.compress((root / 'dashboard_source.html').read_bytes(), mtime=0)
lines = [', '.join(f'0x{x:02X}' for x in data[i:i+16]) for i in range(0,len(data),16)]
(root / 'index_html.h').write_text('#pragma once\n#include <Arduino.h>\n// Generated by tools/embed_dashboard.py\nstatic const uint8_t INDEX_HTML_GZ[] PROGMEM = {\n' + ',\n'.join(lines) + '\n};\nstatic const size_t INDEX_HTML_GZ_LEN = ' + str(len(data)) + ';\n',encoding='utf8')
print(f'Embedded {len(data)} bytes')
